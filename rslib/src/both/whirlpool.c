static uint8_t gf_mul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    int i;
    for (i = 0; i < 8; i++) {
        if (b & 1) {
            p ^= a;
        }
        {
            uint8_t hi = (uint8_t)(a & 0x80);
            a = (uint8_t)(a << 1);
            if (hi) {
                a ^= 0x1d;
            }
        }
        b >>= 1;
    }
    return p;
}

static void rho(uint8_t s[8][8]) {
    uint8_t t[8][8];
    int r, c;
    memcpy(t, s, 64);
    for (r = 0; r < 8; r++) {
        for (c = 0; c < 8; c++) {
            s[r][c] = t[r][(c - r) & 7];
        }
    }
}

static void theta(uint8_t s[8][8]) {
    static const uint8_t C[8] = {1, 1, 4, 1, 8, 5, 2, 9};
    uint8_t t[8][8];
    int r, c, k;
    memcpy(t, s, 64);
    for (r = 0; r < 8; r++) {
        for (c = 0; c < 8; c++) {
            uint8_t v = 0;
            for (k = 0; k < 8; k++) {
                v ^= gf_mul(t[r][k], C[(k - c) & 7]);
            }
            s[r][c] = v;
        }
    }
}

static void process(uint8_t hash[64], const uint8_t block[64]) {
    uint8_t k[8][8], st[8][8], rc[8][8];
    int r, c, round;
    for (r = 0; r < 8; r++) {
        for (c = 0; c < 8; c++) {
            k[r][c] = hash[r * 8 + c];
            st[r][c] = (uint8_t)(block[r * 8 + c] ^ k[r][c]);
        }
    }
    for (round = 1; round <= 10; round++) {
        memset(rc, 0, sizeof(rc));
        for (c = 0; c < 8; c++) {
            rc[0][c] = S[(8 * (round - 1) + c) & 255];
        }
        for (r = 0; r < 8; r++) {
            for (c = 0; c < 8; c++) {
                k[r][c] = S[k[r][c]];
            }
        }
        rho(k);
        theta(k);
        for (r = 0; r < 8; r++) {
            for (c = 0; c < 8; c++) {
                k[r][c] ^= rc[r][c];
            }
        }
        for (r = 0; r < 8; r++) {
            for (c = 0; c < 8; c++) {
                st[r][c] = S[st[r][c]];
            }
        }
        rho(st);
        theta(st);
        for (r = 0; r < 8; r++) {
            for (c = 0; c < 8; c++) {
                st[r][c] ^= k[r][c];
            }
        }
    }
    for (r = 0; r < 8; r++) {
        for (c = 0; c < 8; c++) {
            hash[r * 8 + c] ^= st[r][c] ^ block[r * 8 + c];
        }
    }
}

void rs_whirlpool(const void *data, size_t len, uint8_t out[64]) {
    uint8_t hash[64], block[64];
    const uint8_t *p = data;
    size_t n = len;
    uint64_t bits = (uint64_t)len * 8;
    memset(hash, 0, 64);
    while (n >= 64) {
        process(hash, p);
        p += 64;
        n -= 64;
    }
    memset(block, 0, 64);
    if (n) {
        memcpy(block, p, n);
    }
    block[n] = 0x80;
    if (n >= 32) {
        process(hash, block);
        memset(block, 0, 64);
    }
    {
        int i;
        for (i = 0; i < 8; i++) {
            block[63 - i] = (uint8_t)(bits >> (8 * i));
        }
    }
    process(hash, block);
    memcpy(out, hash, 64);
}
